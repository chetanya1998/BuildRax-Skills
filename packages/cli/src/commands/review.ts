import { promises as fs } from "node:fs";
import path from "node:path";
import { CATALOGUE, type DesignModel } from "@buildrax/design";
import {
  REVIEW_SCHEMA_VERSION,
  validateReviewFile,
  validateReviewInput,
  type Model,
  type RationaleFile,
  type ReviewFile,
} from "@buildrax/ir";
import { buildraxDir, loadModel, loadRationale } from "./data.js";
import { designCommand } from "./design.js";

export const reviewPathFor = (repo: string): string =>
  path.join(buildraxDir(repo), "design-review.json");
export const packPathFor = (repo: string): string => path.join(buildraxDir(repo), "design-pack.md");

const MAX_INPUT_BYTES = 512 * 1024;
const LIST = 40;

/** The brief for the user's coding agent: rules, the design summary, citable ids, output shape. */
export function buildPack(d: DesignModel, model: Model, rationale?: RationaleFile): string {
  const name = (id: string): string => d.c4.elements.find((e) => e.id === id)?.name ?? id;
  const lines: string[] = [
    `# Design review brief: ${d.repo}`,
    "",
    `Generated by \`buildrax design --pack\` from the scan of ${d.scannedAt.slice(0, 10)}. Everything below was`,
    "extracted deterministically from the code, config and docs; nothing here is AI output.",
    "",
    "## Your task",
    "",
    "Review this system's design. Find flaws and risks, name strengths, explain the likely reasons",
    "behind choices that have no recorded rationale, and recommend changes. Then write your review as",
    `JSON (shape below) and run \`buildrax design --import <file>\`. The CLI checks it and stores it`,
    "labelled as AI inference; it never changes the architecture model.",
    "",
    "Rules:",
    "",
    "1. Every item must name the nodes it is about, using ids from the lists below (or `buildrax`",
    "   output). Unknown ids are rejected.",
    "2. Read the code before claiming something about it, and cite what you read as",
    '   `{"file": "path", "line": N}`. Lines are checked against the scanned files.',
    "3. Say what you do not know. A reason you infer is a `rationale` item and its body must say it is",
    "   inferred. Do not present it as the team's decision.",
    "4. Only cite web sources if the user agreed to a web search; give the HTTPS URL and the date you",
    "   read it. Never send source code, secrets or private names in a search.",
    "5. Absent scorecard checks mean a static scan did not see something, not that it is missing.",
    "   Check the code before calling it a flaw.",
    "",
    "## Containers and data stores",
    "",
  ];
  for (const e of d.c4.elements.filter((x) => x.level <= 2))
    lines.push(`- \`${e.id}\` ${e.name} [${e.kind}]: ${e.description}`);
  lines.push("", "Relationships:", "");
  for (const r of d.c4.relations.filter((x) => x.level === 2).slice(0, LIST))
    lines.push(`- ${name(r.from)} -> ${name(r.to)}: ${r.label}`);
  lines.push("", "## Components", "");
  for (const e of d.c4.elements.filter((x) => x.level === 3).slice(0, LIST))
    lines.push(`- \`${e.id}\` ${e.name}${e.tags.length ? ` [${e.tags.join(", ")}]` : ""}`);
  lines.push("", "## Concepts found", "");
  for (const c of d.concepts) lines.push(`- \`${c.id}\` ${c.name}: ${c.detail}`);
  lines.push("", "## Scorecard (absent and risk only)", "");
  for (const c of d.scorecard.checks.filter((x) => x.status !== "present"))
    lines.push(`- ${c.status.toUpperCase()} ${c.category} / ${c.label}: ${c.detail}`);
  const adrs = rationale?.sources.filter((s) => s.kind === "adr") ?? [];
  lines.push("", "## Recorded decisions", "");
  if (!adrs.length)
    lines.push("None found. Use `buildrax why <node>` for comments and commit messages.");
  for (const a of adrs)
    lines.push(`- ${a.title} (${a.status ?? "no status"}) ${a.file ?? ""}: ${a.excerpt}`);
  lines.push("", "## Other citable nodes", "");
  const routes = model.nodes.filter((n) => n.kind === "route").slice(0, LIST);
  const entities = model.nodes.filter((n) => n.kind === "entity").slice(0, LIST);
  for (const n of [...routes, ...entities]) lines.push(`- \`${n.id}\``);
  lines.push(
    "- any `file:<path>` from `buildrax digest`, and any id `buildrax trace`, `buildrax fn` or `buildrax why` print",
    "",
    "## Output shape",
    "",
    "```json",
    JSON.stringify(
      {
        schemaVersion: REVIEW_SCHEMA_VERSION,
        agent: "your agent name",
        items: [
          {
            type: "risk",
            title: "Two services write the same database",
            body: "What you found, why it matters, and what you are unsure about.",
            severity: "medium",
            nodes: ["database:postgres"],
            evidence: [{ file: "path/to/file.ts", line: 12 }],
            concept: "relational-database",
          },
        ],
      },
      null,
      2,
    ),
    "```",
    "",
    "`type`: flaw, risk, strength, rationale or recommendation. `severity` (flaw and risk): high,",
    'medium or low. Optional `sources`: `[{ "url": "https://…", "title": "…", "accessed": "YYYY-MM-DD" }]`.',
    `Concept ids: ${CATALOGUE.map((c) => c.id).join(", ")}.`,
  );
  return `${lines.join("\n")}\n`;
}

export async function packCommand(
  repo: string,
  out?: string,
): Promise<{ path: string; text: string }> {
  const [d, model, rationale] = await Promise.all([
    designCommand(repo),
    loadModel(repo),
    loadRationale(repo).catch(() => undefined),
  ]);
  const text = buildPack(d, model, rationale);
  const file = out ? path.resolve(out) : packPathFor(repo);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, text);
  return { path: file, text };
}

const PRIVATE_HOST =
  /^(localhost|.*\.local|.*\.internal|.*\.lan|\d{1,3}(\.\d{1,3}){3}|\[.*\]|0\.0\.0\.0)$/i;
// eslint-disable-next-line no-control-regex -- strip control characters from agent text
const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g;

/** Check an agent's review against the model; returns the file to store, or every problem found. */
export function checkReview(
  raw: unknown,
  model: Model,
  d: DesignModel,
  now: string,
): { ok: true; file: ReviewFile } | { ok: false; errors: string[] } {
  const shape = validateReviewInput(raw);
  if (!shape.ok || !shape.review) return { ok: false, errors: shape.errors };
  const ids = new Set([...model.nodes.map((n) => n.id), ...d.c4.elements.map((e) => e.id)]);
  const lines = new Map(
    model.nodes
      .filter((n) => n.kind === "file" && n.path)
      .map((n) => [n.path!, Number(n.meta?.["lines"] ?? n.evidence[0]?.endLine ?? 0)] as const),
  );
  const concepts = new Set(CATALOGUE.map((c) => c.id));
  const errors: string[] = [];
  shape.review.items.forEach((it, i) => {
    const at = `items.${i}`;
    for (const n of it.nodes) if (!ids.has(n)) errors.push(`${at}.nodes: unknown id "${n}"`);
    for (const e of it.evidence ?? []) {
      const max = lines.get(e.file.replace(/^\.\//, ""));
      if (max === undefined) errors.push(`${at}.evidence: "${e.file}" is not a scanned file`);
      else if (max && e.line > max)
        errors.push(`${at}.evidence: ${e.file} has ${max} lines, not ${e.line}`);
    }
    for (const s of it.sources ?? []) {
      let url: URL | undefined;
      try {
        url = new URL(s.url);
      } catch {
        /* reported below */
      }
      if (!url || url.protocol !== "https:" || PRIVATE_HOST.test(url.hostname))
        errors.push(`${at}.sources: "${s.url}" must be a public https URL`);
    }
    if (it.concept && !concepts.has(it.concept))
      errors.push(`${at}.concept: unknown concept "${it.concept}"`);
    if (it.severity && it.type !== "flaw" && it.type !== "risk")
      errors.push(`${at}.severity: only flaw and risk items take a severity`);
  });
  if (errors.length) return { ok: false, errors };
  const clean = (s: string): string => s.replace(CONTROL, "").trim();
  return {
    ok: true,
    file: {
      schemaVersion: REVIEW_SCHEMA_VERSION,
      ...(shape.review.agent ? { agent: clean(shape.review.agent) } : {}),
      importedAt: now,
      modelScannedAt: model.meta.scannedAt,
      items: shape.review.items.map((it, i) => ({
        ...it,
        title: clean(it.title),
        body: clean(it.body),
        evidence: it.evidence?.map((e) => ({ ...e, file: e.file.replace(/^\.\//, "") })),
        id: `review:${i + 1}`,
        provenance: "ai" as const,
        cited: !!it.sources?.length,
      })),
    },
  };
}

export async function importCommand(
  repo: string,
  file: string,
  now = new Date().toISOString(),
): Promise<ReviewFile> {
  const stat = await fs.stat(file);
  if (stat.size > MAX_INPUT_BYTES) throw new Error(`${file} is larger than 512 KB`);
  let raw: unknown;
  try {
    raw = JSON.parse(await fs.readFile(file, "utf8"));
  } catch (err) {
    throw new Error(`${file} is not valid JSON: ${String(err)}`, { cause: err });
  }
  const [model, d] = await Promise.all([loadModel(repo), designCommand(repo)]);
  const res = checkReview(raw, model, d, now);
  if (!res.ok)
    throw new Error(
      `review rejected, nothing stored. Fix these and import again:\n${res.errors.map((e) => `  - ${e}`).join("\n")}`,
    );
  const out = reviewPathFor(repo);
  await fs.writeFile(`${out}.tmp`, `${JSON.stringify(res.file, null, 2)}\n`);
  await fs.rename(`${out}.tmp`, out);
  return res.file;
}

/** The stored review, or undefined when none was imported. */
export async function loadReview(repo: string): Promise<ReviewFile | undefined> {
  let raw: unknown;
  try {
    raw = JSON.parse(await fs.readFile(reviewPathFor(repo), "utf8"));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return undefined;
    throw err;
  }
  const checked = validateReviewFile(raw);
  if (!checked.ok || !checked.file)
    throw new Error(`design-review.json is invalid:\n${checked.errors.slice(0, 5).join("\n")}`);
  return checked.file;
}
